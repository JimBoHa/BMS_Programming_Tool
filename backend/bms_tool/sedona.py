"""Native Sedona compilation and Sox access through the actual upstream SDK.

SAB is an executable Sedona application, never a renamed graph. Generated kits
require a compatible SCode image. Commercial controllers may restrict kit/image
installation; this adapter does not override those restrictions.
"""

