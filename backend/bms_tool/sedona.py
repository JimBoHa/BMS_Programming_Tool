ROOT = Path(__file__).resolve().parents[2]
_COMPILER_LOCK = threading.RLock()
_ACTIVE_TOOL_LOCK = threading.local()


@contextmanager
def _tool_lock(sdk):
    # The SDK's kit/manifest database is shared by servers and command-line
    # clients. A thread lock alone does not serialize separate processes.
    with _COMPILER_LOCK:
        if getattr(_ACTIVE_TOOL_LOCK, "sdk", None) == str(sdk):
            yield
            return
        with file_lock(
            sdk / ".bms-toolchain.lock",
            timeout=45,
            busy="The Sedona SDK is busy rebuilding or compiling.",
        ):
            _ACTIVE_TOOL_LOCK.sdk = str(sdk)
            try:
                yield
            finally:
                _ACTIVE_TOOL_LOCK.sdk = None


def toolchain():
    sdk = Path(os.environ.get("BMS_SEDONA_HOME", ROOT.parent / "Reference_Sources/sedona"))
    java = os.environ.get("BMS_JAVA")
    if not java:
        candidates = sorted((ROOT.parent / ".toolchain").glob("jdk-17*/Contents/Home/bin/java"))
        java = str(candidates[-1]) if candidates else "java"
    if not all((sdk / "lib" / jar).is_file() for jar in ("sedona.jar", "sedonac.jar")):
        raise ConversionError("Sedona SDK is unavailable. Run scripts/setup_sedona.py first.")
    return sdk.resolve(), java


def _run(args, *, content=None, cwd=None, timeout=45):
    try:
        result = subprocess.run(
            list(map(str, args)), input=content, cwd=cwd, capture_output=True, timeout=timeout
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise ConversionError("Native tool could not finish: " + type(exc).__name__) from exc
    if result.returncode:
        # Never echo the request, which can contain controller credentials.
        message = (result.stdout + result.stderr).decode(errors="replace")[-4000:]
        raise ConversionError("Native tool rejected the operation: " + message)
    return result.stdout


def compiler(sdk, java, *args):
    with _tool_lock(sdk):
        return _run(
            [
                java,
                "-Xmx256m",
                "-Dsedona.home=" + str(sdk),
                "-cp",
                os.pathsep.join(str(sdk / "lib" / j) for j in ("sedona.jar", "sedonac.jar")),
                "sedonac.Main",
                *args,
            ]
        )


def _expression(text):
    replacements = {
        "TRUE": "true",
        "FALSE": "false",
        "AND": "&&",
        "OR": "||",
        "NOT": "!",
        "MIN": "minimum",
        "MAX": "maximum",
        "ABS": "absolute",
    }
    text = re.sub(r"\b(?:TRUE|FALSE|AND|OR|NOT|MIN|MAX|ABS)\b", lambda m: replacements[m[0]], text)
    # Sedona deliberately considers two null/NaN floats equal. Its null literal
    # tests NaN; the IEEE x<>x idiom used by ST would give the wrong result here.
    text = re.sub(r"\b(\w+)\s*<>\s*\1\b", r"\1 = null", text)
    text = text.replace("<>", "!=")
    text = re.sub(r"(?<![<>=!])=(?!=)", "==", text)
    return re.sub(r"\b(?:\d+\.\d+(?:[eE][+-]?\d+)?|\d+[eE][+-]?\d+)\b", lambda m: m[0] + "f", text)


def kit_source(program, *, profile=CURRENT):
    """Lower our bounded ST grammar to Sedona; never evaluate imported source."""
    core = program.model_copy(deep=True)
    core.metadata.pop("native_sedona", None)
    declarations, body = structured_text_parts(core, profile=profile)
    reflected = {
        name for group in ("inputVars", "outputVars") for name, _, _ in declarations[group]
    }
    if len(reflected) > 180:
        raise ConversionError("Sedona export exceeds this adapter's 180 reflected-slot limit.")
    lines = [
        "// Generated by BMS Studio. SPDX-License-Identifier: Apache-2.0",
        "class Graph extends Component",
        "{",
    ]
    if profile != LEGACY:
        info = source_profile(profile)
        lines.insert(1, "// Source generator: " + info["id"] + " rules " + info["rules_sha256"])
    for group, variables in declarations.items():
        for name, kind, initial in variables:
            prefix = (
                "@config property "
                if group == "inputVars"
                else "@readonly property "
                if group == "outputVars"
                else "private "
            )
            typ = {"REAL": "float", "BOOL": "bool", "INT": "int"}[kind]
            lines.append(
                "  "
                + prefix
                + typ
                + " "
                + name
                + (" = " + _expression(initial) if initial is not None else "")
            )
    lines += [
        "  @config property bool autoScan = false",
        "  @readonly property int successfulScans",
        "  virtual override void execute() { if (autoScan) scan() }",
        "  action void step() { scan() }",
        "  private float minimum(float a, float b) { return a < b ? a : b }",
        "  private float maximum(float a, float b) { return a > b ? a : b }",
        "  private float absolute(float a) { return a < 0f ? -a : a }",
        "  private void scan()",
        "  {",
    ]
    body = re.sub(r"\(\*.*?\*\)", "", body, flags=re.S)
    # The source is generated internally from typed graphs. Split statement/control
    # boundaries before lowering so nested inline IF statements remain balanced.
    tokens = []
    pattern = re.compile(
        r"\s*(\b(?:IF|ELSIF)\b.*?\bTHEN\b|\bELSE\b|\bEND_IF\b;?|\bRETURN;|"
        r"[A-Za-z]\w*\s*:=\s*[^;]+;)",
        re.S,
    )
    offset = 0
    while body[offset:].strip():
        match = pattern.match(body, offset)
        if not match:
            raise ConversionError("Unrecognized internal compiler statement.")
        tokens.append(match[1])
        offset = match.end()
    for token in tokens:
        token = token.strip()
        if not token:
            continue
        if token.startswith("IF ") or token.startswith("ELSIF "):
            prior = "} else " if token.startswith("ELSIF") else ""
            condition = re.sub(r"^(?:IF|ELSIF)\s+|\s+THEN$", "", token)
            lines.append("    " + prior + "if (" + _expression(condition) + ") {")
        elif token == "ELSE":
            lines.append("    } else {")
        elif token.startswith("END_IF"):
            lines.append("    }")
        elif token == "RETURN;":
            lines.append("    return;")
        else:
            match = re.fullmatch(r"(\w+)\s*:=\s*(.*);", token, re.S)
            if not match:
                raise ConversionError("Unrecognized internal compiler statement.")
            name, expression = match.groups()
            lines.append(
                f"    {name} {':=' if name in reflected else '='} {_expression(expression)};"
            )
    lines += ["    successfulScans := successfulScans + 1", "  }", "}"]
    return ("\n".join(lines) + "\n").encode()


def application_xml(kit, *, auth=None, port=1876, scan_seconds=1.0, native_document=None):
    root = XML.Element("sedonaApp")
    schema = XML.SubElement(root, "schema")
    for name in (
        ["sys", "platUnix", kit]
        + (["types", "math"] if auth or native_document else [])
        + (["inet", "sox"] if auth else [])
    ):
        XML.SubElement(schema, "kit", {"name": name})
    app = XML.SubElement(root, "app")
    XML.SubElement(app, "prop", {"name": "appName", "val": "bms-studio"})
    # The simulator invokes Graph.step explicitly with its own clock/timestep.
    # Fast service polling does not advance the control program's simulated time.
    milliseconds = scan_seconds * 1000
    if not auth and abs(round(milliseconds) - milliseconds) > 1e-6:
        raise ConversionError("Native automatic scan periods require whole milliseconds.")
    XML.SubElement(
        app, "prop", {"name": "scanPeriod", "val": str(5 if auth else round(milliseconds))}
    )
    service = XML.SubElement(app, "comp", {"name": "service", "type": "sys::Folder"})
    XML.SubElement(service, "comp", {"name": "plat", "type": "platUnix::UnixPlatformService"})
    if auth:
        user, password = auth
        import base64

        credential = base64.b64encode(hashlib.sha1(f"{user}:{password}".encode()).digest()).decode()
        users = XML.SubElement(service, "comp", {"name": "users", "type": "sys::UserService"})
        person = XML.SubElement(users, "comp", {"name": user, "type": "sys::User"})
        for name, val in {"cred": credential, "perm": "2147483647", "prov": "255"}.items():
            XML.SubElement(person, "prop", {"name": name, "val": val})
        sox = XML.SubElement(service, "comp", {"name": "sox", "type": "sox::SoxService"})
        XML.SubElement(sox, "prop", {"name": "port", "val": str(port)})
    logic = XML.SubElement(app, "comp", {"name": "logic", "type": "sys::Folder"})
    graph = XML.SubElement(logic, "comp", {"name": "graph", "type": kit + "::Graph"})
    XML.SubElement(graph, "prop", {"name": "autoScan", "val": "false" if auth else "true"})
    links = XML.SubElement(root, "links")
    if auth or native_document:
        from .native_document import NativeDocument

        NativeDocument.model_validate(native_document or {}).attach(app, links)
    return XML.tostring(root, encoding="utf-8", xml_declaration=True)


def kit_name(program, *, profile=CURRENT):
    info = source_profile(profile)
    data = canonical(program)
    if profile != LEGACY:
        data = info["id"].encode() + b"\0" + info["rules_sha256"].encode() + b"\0" + data
    return "studio" + hashlib.sha256(data).hexdigest()[:10]


def compile_program(program, directory, *, auth=None, port=1876):
    source = kit_source(program)
    sdk, java = toolchain()
    directory = Path(directory).resolve()
    directory.mkdir(parents=True, exist_ok=True)
    name = kit_name(program)
    definition = (
        f'<sedonaKit name="{name}" vendor="studio" includeSource="true" '
        'description="Generated BMS Studio control graph">'
        '<depend on="sys 1.2+"/><source dir="."/></sedonaKit>'
    ).encode()
    (directory / "Graph.sedona").write_bytes(source)
    (directory / "kit.xml").write_bytes(definition)
    (directory / "app.sax").write_bytes(
        application_xml(
            name,
            auth=auth,
            port=port,
            scan_seconds=program.scan_seconds,
            native_document=program.metadata.get("native_sedona"),
        )
    )
    with _tool_lock(sdk):
        compiler(sdk, java, directory, "-kitVersion", "1.0.0")
        compiler(sdk, java, directory / "app.sax")
        image = XML.Element(
            "sedonaCode",
            {
                "endian": "little",
                "blockSize": "4",
                "refSize": "8",
                "main": "sys::Sys.main",
                "debug": "true",
                "test": "false",
            },
        )
        for kit in [
            "sys",
            "inet",
            "sox",
            "platUnix",
            "types",
            "math",
            "serial",
            "datetime",
            "datetimeStd",
            name,
        ]:
            XML.SubElement(image, "depend", {"on": kit + " 1.0+"})
        (directory / "kits.xml").write_bytes(XML.tostring(image))
        compiler(sdk, java, directory / "kits.xml")
        files = sorted((sdk / "kits" / name).glob("*.kit"))
        if len(files) != 1:
            raise ConversionError("Compiler did not produce exactly one native kit.")
        (directory / "native.kit").write_bytes(files[0].read_bytes())
    return {"kit": name, "source": source, "sdk": str(sdk), "source_generator": source_profile()}


def export_bundle(program):
    with tempfile.TemporaryDirectory(prefix="bms-sedona-") as tmp:
        path = Path(tmp)
        build = compile_program(program, path)
        files = {
            name: (path / name).read_bytes()
            for name in (
                "Graph.sedona",
                "kit.xml",
                "app.sax",
                "app.sab",
                "kits.xml",
                "kits.scode",
                "native.kit",
            )
        }
        files["program.bms.json"] = canonical(program)
        files["README.txt"] = (
            b"Native Sedona application and generated kit. No credentials or network service included.\n"
            b"kits.scode targets the local experimental 64-bit Unix simulator.\n"
            b"The exported application scans automatically at program.scan_seconds.\n"
            b"Calendar inputs and physical I/O mappings must be supplied by the destination runtime.\n"
            b"A physical controller needs a platform-specific SCode image containing this kit;\n"
            b"verify vendor permission, native services and platform ABI before installation.\n"
            b"These files do not run on JCI VMA/FX, ALC, Spyder or Niagara firmware.\n"
            b"The SCode image includes Tridium Sedona Framework code, copyright 2006-2013, AFL-3.0.\n"
            b"Source: https://github.com/linsong/sedona at 406b11f3816fb00db6482640f9cf3397b874b515.\n"
            b"Build changes: scripts/setup_sedona.py in BMS Studio reproduces the 64-bit port.\n"
        )
        files["Sedona-LICENSE.md"] = (Path(build["sdk"]) / "LICENSE.md").read_bytes()
        files["manifest.json"] = json.dumps(
            {
                "schema": "bms-sedona-bundle/2",
                "source_generator": build["source_generator"],
                "kit": build["kit"],
                "files": {name: hashlib.sha256(data).hexdigest() for name, data in files.items()},
            },
            indent=2,
        ).encode()
        out = io.BytesIO()
        with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as archive:
            for name, data in files.items():
                archive.writestr(name, data)
        return out.getvalue()


def import_bundle(content):
    if len(content) > 8 * 1024 * 1024:
        raise ConversionError("Sedona bundle exceeds 8 MiB.")
    with zipfile.ZipFile(io.BytesIO(content)) as archive:
        infos = archive.infolist()
        expected = {
            "Graph.sedona",
            "kit.xml",
            "app.sax",
            "app.sab",
            "kits.xml",
            "kits.scode",
            "native.kit",
            "program.bms.json",
            "README.txt",
            "Sedona-LICENSE.md",
            "manifest.json",
        }
        if len(infos) != len(expected) or {i.filename for i in infos} != expected:
            raise ConversionError("Unexpected or duplicate Sedona bundle members.")
        if sum(i.file_size for i in infos) > 32 * 1024 * 1024:
            raise ConversionError("Expanded Sedona bundle exceeds 32 MiB.")
        manifest = read_profile_json(archive.read("manifest.json"), limit=64 * 1024)
        if not isinstance(manifest, dict) or manifest.get("schema") not in (
            "bms-sedona-bundle/1",
            "bms-sedona-bundle/2",
        ):
            raise ConversionError("Unknown Sedona bundle schema.")
        legacy = manifest["schema"] == "bms-sedona-bundle/1"
        expected_fields = {"schema", "kit", "files"} | (set() if legacy else {"source_generator"})
        if set(manifest) != expected_fields:
            raise ConversionError("Unknown or conflicting Sedona source-generator profile markers.")
        if not legacy:
            verify_source_profile(manifest["source_generator"])
        if (
            not isinstance(manifest.get("files"), dict)
            or set(manifest["files"]) != expected - {"manifest.json"}
            or any(
                not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest)
                for digest in manifest["files"].values()
            )
        ):
            raise ConversionError("Invalid Sedona bundle checksum manifest.")
        for name, digest in manifest["files"].items():
            if hashlib.sha256(archive.read(name)).hexdigest() != digest:
                raise ConversionError("Sedona bundle checksum mismatch.")
        program = Program.model_validate_json(archive.read("program.bms.json"))
        profile = LEGACY if legacy else CURRENT
        kit = kit_name(program, profile=profile)
        if (
            manifest.get("kit") != kit
            or archive.read("Graph.sedona")
            != kit_source(
                _legacy_source_projection(program) if legacy else program, profile=profile
            )
            or archive.read("app.sax")
            != application_xml(
                kit,
                scan_seconds=program.scan_seconds,
                native_document=program.metadata.get("native_sedona"),
            )
        ):
            raise ConversionError("Sedona source differs from the embedded graph; import refused.")
        # Uploaded binaries are never loaded or executed on import.
        return program


def sox_request(host, port, user, password, operations):
    sdk, java = toolchain()
    source = Path(__file__).parent / "sedona_bridge/SoxBridge.java"
    cache = ROOT / ".state/sedona-bridge" / hashlib.sha256(source.read_bytes()).hexdigest()[:12]
    with _tool_lock(sdk):
        if not (cache / "SoxBridge.class").is_file():
            cache.mkdir(parents=True, exist_ok=True)
            javac = Path(java).with_name("javac")
            _run(
                [javac, "--release", "8", "-classpath", sdk / "lib/sedona.jar", "-d", cache, source]
            )
    request = XML.Element(
        "request", {"host": host, "port": str(port), "user": user, "password": password}
    )
    for operation in operations:
        XML.SubElement(
            request, operation["op"], {k: str(v) for k, v in operation.items() if k != "op"}
        )
    with _tool_lock(sdk):
        result = _run(
            [
                java,
                "-Xmx256m",
                "-Dsedona.home=" + str(sdk),
                "-cp",
                os.pathsep.join([str(cache), str(sdk / "lib/sedona.jar")]),
                "SoxBridge",
            ],
            content=XML.tostring(request),
            timeout=60,
        )
    # Upstream SDK logging can precede XML; only the bridge's result is parsed.
    start = result.find(b"<?xml")
    if start < 0:
        raise ConversionError("Sox bridge returned no structured response.")
    return SafeXML.fromstring(result[start:])
